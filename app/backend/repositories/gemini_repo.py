"""Gemini repository wrapping google-genai SDK for multimodal generation."""

import mimetypes
from pathlib import Path
from typing import Any, Optional

from google import genai
from google.genai import types

from app.backend.config.settings import AppSettings
from app.backend.entities.ai_models import ConceptList


class GeminiRepo:
    """Repository managing Gemini structured outputs and image generation via separate clients."""

    def __init__(
        self,
        image_client: Optional[Any] = None,
        concepts_client: Optional[Any] = None,
        image_model: Optional[str] = None,
        concepts_model: Optional[str] = None,
    ) -> None:
        """Initialize Gemini repository with separate clients for image and concept generation."""
        settings = AppSettings.load()
        if image_client is not None:
            self._image_client = image_client
        else:
            self._image_client = genai.Client(api_key=settings.GEMINI_IMAGE_API_KEY)
        if concepts_client is not None:
            self._concepts_client = concepts_client
        else:
            self._concepts_client = genai.Client(
                api_key=settings.GEMINI_CONCEPTS_API_KEY
            )
        self._image_model = image_model or settings.GEMINI_IMAGE_MODEL
        self._concepts_model = concepts_model or settings.GEMINI_CONCEPTS_MODEL

    async def generate_image(self, prompt: str, output_path: str) -> str:
        """Generate image using Gemini image model and save output bytes to disk."""
        target_file = Path(output_path)
        target_file.parent.mkdir(parents=True, exist_ok=True)

        config = types.GenerateContentConfig(
            response_modalities=["IMAGE"],
        )

        response = await self._image_client.aio.models.generate_content(
            model=self._image_model,
            contents=prompt,
            config=config,
        )

        image_bytes: Optional[bytes] = None
        if hasattr(response, "candidates") and response.candidates:
            for candidate in response.candidates:
                if hasattr(candidate, "content") and candidate.content:
                    for part in candidate.content.parts:
                        if (
                            getattr(part, "inline_data", None) is not None
                            and part.inline_data.data
                        ):
                            image_bytes = part.inline_data.data
                            break
                if image_bytes:
                    break

        if not image_bytes:
            raise ValueError(f"No image generated by {self._image_model} model.")

        temp_path = target_file.parent / f".tmp_{target_file.name}"
        temp_path.write_bytes(image_bytes)
        temp_path.replace(target_file)

        return str(target_file.resolve())

    async def generate_structured_concepts(
        self, prompt: str, image_path: str
    ) -> ConceptList:
        """Analyze image and prompt to produce structured ConceptList via Gemini 1.5 Pro."""
        path_obj = Path(image_path)
        image_bytes = path_obj.read_bytes()

        mime_type, _ = mimetypes.guess_type(str(path_obj))
        mime_type = mime_type or "image/jpeg"

        image_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)

        config = types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=ConceptList,
        )

        response = await self._concepts_client.aio.models.generate_content(
            model=self._concepts_model,
            contents=[image_part, prompt],
            config=config,
        )

        if hasattr(response, "text") and response.text:
            return ConceptList.model_validate_json(response.text)

        raise ValueError("Empty or invalid structured response from Gemini 1.5 Pro.")
